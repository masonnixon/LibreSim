class PythonCodeGenerator(LanguageGenerator):
    """Generate Python simulation code."""

    def generate(
        self,
        model_info: CompiledModelInfo,
        config: Any,
    ) -> GeneratedProject:
        """Generate a complete Python project."""
        project = GeneratedProject(
            name=config.project_name,
            language=Language.PYTHON,
        )

        # Generate blocks.py - all block class definitions
        blocks_code = self._generate_blocks_file(model_info)
        project.add_file("blocks.py", blocks_code)

        # Generate integration.py - integration methods
        integration_code = self.generate_integration_code(config.integration_method)
        project.add_file("integration.py", integration_code)

        # Generate simulation.py - main model class and step function
        simulation_code = self._generate_simulation_file(model_info, config)
        project.add_file("simulation.py", simulation_code)

        # Generate main.py - example runner
        if config.include_main:
            main_code = self.generate_main_code(model_info, config)
            project.add_file("main.py", main_code)

        # Generate requirements.txt
        requirements = self._generate_requirements()
        project.add_file("requirements.txt", requirements)

        # Generate setup.py
        setup_code = self._generate_setup(config)
        project.add_file("setup.py", setup_code)

        # Generate README.md
        readme = self._generate_readme(model_info, config)
        project.add_file("README.md", readme)

        # Generate Dockerfile for compilation
        dockerfile = self._generate_dockerfile(config)
        project.add_file("Dockerfile", dockerfile)

        # Generate docker build and run scripts
        build_script = self._generate_build_script(config)
        project.add_file("build.sh", build_script)
        run_script = self._generate_run_script(config)
        project.add_file("run.sh", run_script)

        # Validate generated Python code
        self._validate_python_code(project)

        return project

    def _validate_python_code(self, project: GeneratedProject) -> None:
        """Validate that generated Python code has no syntax errors.

        Raises:
            SyntaxError: If any Python file has syntax errors
        """
        for file in project.files:
            if file.path.endswith(".py"):
                try:
                    compile(file.content, file.path, "exec")
                except SyntaxError as e:
                    # Add more context to the error
                    error_msg = (
                        f"Syntax error in generated {file.path}:\n"
                        f"  Line {e.lineno}: {e.text.strip() if e.text else '(no text)'}\n"
                        f"  Error: {e.msg}"
                    )
                    # Re-raise with better message
                    raise SyntaxError(error_msg) from e

    def generate_block_code(self, block: BlockInfo) -> str:
        """Generate code for a single block."""
        template_fn = get_block_template(block.type)
        if template_fn is None:
            # Fallback to passthrough
            return self._generate_passthrough_block(block)

        # Call template function with block and class name
        class_name = f"Block_{self.sanitize_identifier(block.id)}"
        return template_fn(block, class_name)

