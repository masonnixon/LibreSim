    def _generate_simulation_file(
        self,
        model_info: CompiledModelInfo,
        config: Any,
    ) -> str:
        """Generate simulation.py with Model class and run function."""
        # Build block instantiation code
        block_inits = []
        for block in model_info.blocks:
            class_name = f"Block_{self.sanitize_identifier(block.id)}"
            var_name = self.get_block_var_name(block)
            block_inits.append(f"        self.{var_name} = {class_name}()")

        # Build connection wiring code (for wire_connections method)
        connection_code = self._generate_connection_code(model_info)

        # Build per-block wiring map (for inline wiring during step)
        block_wiring = self._generate_per_block_wiring(model_info)

        # Build update order code (8 spaces - inside method body)
        # Each block has its inputs wired from upstream outputs, then updates
        update_calls: list[str] = []
        for block_id in model_info.execution_order:
            block_match = next((b for b in model_info.blocks if b.id == block_id), None)
            if block_match is not None:
                var_name = self.get_block_var_name(block_match)
                # Add wiring for this block's inputs (if any)
                if block_id in block_wiring:
                    for wire_line in block_wiring[block_id]:
                        update_calls.append(wire_line)
                update_calls.append(f"        self.{var_name}.update(t)")

        # Build integrator list for state propagation
        integrator_list: list[str] = []
        multi_state_list: list[str] = []  # Blocks with propagate_states method
        for block_id in model_info.integrator_blocks:
            block_match = next((b for b in model_info.blocks if b.id == block_id), None)
            if block_match is not None:
                var_name = self.get_block_var_name(block_match)
                integrator_list.append(f"self.{var_name}")
                # Multi-state blocks need additional propagation
                if block_match.type in (
                    "transfer_function",
                    "state_space",
                    "second_order",
                    "pid_controller",
                ):
                    multi_state_list.append(f"self.{var_name}")

        # Build output recording code
        output_recording = self._generate_output_recording(model_info)

        # Generate multi-state propagation code (if any)
        multi_state_propagation = ""
        if multi_state_list:
            multi_state_propagation = """
            # Propagate multi-state blocks (transfer functions, state-space)
            for block in model._multi_state_blocks:
                if hasattr(block, 'propagate_states'):
                    block.propagate_states(dt, kpass)"""

